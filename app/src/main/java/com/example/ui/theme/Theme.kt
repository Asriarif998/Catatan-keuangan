@Immutable
data class FinanceColors(
    val income: Color,
    val incomeContainer: Color,
    val expense: Color,
    val expenseContainer: Color,
    val transfer: Color,
    val transferContainer: Color,
)

val LocalFinanceColors = staticCompositionLocalOf {
    FinanceColors(
        income = IncomeGreenLight,
        incomeContainer = IncomeContainerLight,
        expense = ExpenseRedLight,
        expenseContainer = ExpenseContainerLight,
        transfer = TransferBlueLight,
        transferContainer = TransferContainerLight,
    )
}

private val AppShapes = Shapes(
    small = RoundedCornerShape(10.dp),
    medium = RoundedCornerShape(16.dp),
    large = RoundedCornerShape(22.dp),
    extraLarge = RoundedCornerShape(28.dp),
)

@Composable
fun DompetKuTheme(
    themeMode: ThemeMode = ThemeMode.SYSTEM,
    content: @Composable () -> Unit,
) {
    val useDarkTheme = when (themeMode) {
        ThemeMode.SYSTEM -> isSystemInDarkTheme()
        ThemeMode.LIGHT -> false
        ThemeMode.DARK -> true
    }

    val colorScheme = if (useDarkTheme) DarkColorScheme else LightColorScheme
    val financeColors = if (useDarkTheme) {
        FinanceColors(
            income = IncomeGreenDark,
            incomeContainer = IncomeContainerDark,
            expense = ExpenseRedDark,
            expenseContainer = ExpenseContainerDark,
            transfer = TransferBlueDark,
            transferContainer = TransferContainerDark,
        )
    } else {
        FinanceColors(
            income = IncomeGreenLight,
            incomeContainer = IncomeContainerLight,
            expense = ExpenseRedLight,
            expenseContainer = ExpenseContainerLight,
            transfer = TransferBlueLight,
            transferContainer = TransferContainerLight,
        )
    }

    CompositionLocalProvider(LocalFinanceColors provides financeColors) {
        MaterialTheme(
            colorScheme = colorScheme,
            typography = AppTypography,
            shapes = AppShapes,
            content = content,
        )
    }
}
